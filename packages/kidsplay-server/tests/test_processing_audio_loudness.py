def test_clipped_master_converges_under_the_ceiling(
    clipped_master: Path, tmp_path: Path
) -> None:
    """Regression (#61): lowering loudnorm's ceiling by the overshoot did not
    converge for loud, clipped masters; the item failed after three attempts.
    A gain reduction after loudnorm does."""
    source = clipped_master
    measured = measure_loudness(source)
    assert measured.true_peak_dbtp > 5  # a clipped master

    out = tmp_path / "out.mp3"
    result = normalize_loudness(source, out, TARGET)

    after = measure_loudness(out)
    assert after.true_peak_dbtp <= TARGET.true_peak_dbtp
    assert result.output_true_peak_dbtp == pytest.approx(after.true_peak_dbtp, abs=0.05)
    # Ends a little under the target; loudnorm's own estimate of a limited
    # file's loudness is a few tenths of a dB optimistic.
    assert result.output_lufs < TARGET.integrated_lufs
    assert result.output_lufs == pytest.approx(after.integrated_lufs, abs=0.5)
    assert result.mode == "dynamic"
    # The gain reduction is recorded as a lower gain, not hidden.
    assert result.gain_db == pytest.approx(
        after.integrated_lufs - measured.integrated_lufs, abs=0.5
    )


def test_clipped_master_logs_the_peaks_at_info(
    clipped_master: Path, tmp_path: Path, caplog: pytest.LogCaptureFixture
) -> None:
    with caplog.at_level(logging.INFO, logger=audio.logger.name):
        normalize_loudness(clipped_master, tmp_path / "out.mp3", TARGET)
    (record,) = [r for r in caplog.records if r.levelno == logging.INFO]
    assert "dBTP over the -1.50 ceiling" in record.getMessage()
    assert "gain reduction" in record.getMessage()


