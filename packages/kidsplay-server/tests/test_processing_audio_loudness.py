def _to_opus(source: Path, dest: Path) -> Path:
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(source)]
        + ["-c:a", "libopus", "-ar", "48000", str(dest)],
        check=True,
    )
    return dest


