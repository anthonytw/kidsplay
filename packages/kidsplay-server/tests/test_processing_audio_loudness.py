def _measurement(i: float, tp: float) -> LoudnessMeasurement:
    return LoudnessMeasurement(i, tp, 3.0, i - 10, 0.1)


class TestPeakRetries:
    @pytest.fixture
    def encodes(self, monkeypatch: pytest.MonkeyPatch) -> list[tuple[float, float]]:
        """Record the ``(ceiling, trim_db)`` each ``_encode`` call is given."""
        calls: list[tuple[float, float]] = []

        def fake_encode(
            source: Path,
            dest: Path,
            target: LoudnessTarget,
            measured: LoudnessMeasurement,
            sample_rate: int,
            cancel: threading.Event | None = None,
            trim_db: float = 0.0,
        ) -> tuple[str, float]:
            calls.append((target.true_peak_dbtp, trim_db))
            return "linear", -16.0 - trim_db

        def fake_measure(
            path: Path,
            target: LoudnessTarget | None = None,
            cancel: threading.Event | None = None,
        ) -> LoudnessMeasurement:
            return _measurement(-30.0, -20.0)

        monkeypatch.setattr(audio, "_encode", fake_encode)
        monkeypatch.setattr(audio, "measure_loudness", fake_measure)
        monkeypatch.setattr(
            audio, "_output_sample_rate", lambda path, cancel=None: 44100
        )
        return calls

    def _fake_peaks(self, monkeypatch: pytest.MonkeyPatch, peaks: list[float]) -> None:
        monkeypatch.setattr(
            audio, "measure_true_peak", lambda path, cancel=None: peaks.pop(0)
        )

    def test_overshoot_trims_the_gain_and_retries(
        self,
        monkeypatch: pytest.MonkeyPatch,
        encodes: list[tuple[float, float]],
        tmp_path: Path,
    ) -> None:
        self._fake_peaks(monkeypatch, [-1.2, -1.6])
        result = normalize_loudness(tmp_path / "in", tmp_path / "out", TARGET)
        # loudnorm's ceiling stays; the retry is trimmed by the 0.3 dB
        # overshoot plus a 0.1 dB margin.
        assert encodes[0] == (-1.5, 0.0)
        assert encodes[1] == (-1.5, pytest.approx(0.4))
        assert result.output_true_peak_dbtp == -1.6
        # The recorded loudness includes the trim.
        assert result.output_lufs == pytest.approx(-16.4)
        assert result.gain_db == pytest.approx(13.6)

    def test_trims_accumulate_with_a_growing_margin(
        self,
        monkeypatch: pytest.MonkeyPatch,
        encodes: list[tuple[float, float]],
        tmp_path: Path,
    ) -> None:
        self._fake_peaks(monkeypatch, [-1.0, -1.1, -1.6])
        normalize_loudness(tmp_path / "in", tmp_path / "out", TARGET)
        # 0.5 + 0.1, then 0.4 + 0.2 more.
        assert [t for _, t in encodes] == pytest.approx([0.0, 0.6, 1.2])

    def test_peak_exactly_at_ceiling_accepted(
        self,
        monkeypatch: pytest.MonkeyPatch,
        encodes: list[tuple[float, float]],
        tmp_path: Path,
    ) -> None:
        self._fake_peaks(monkeypatch, [-1.5])
        normalize_loudness(tmp_path / "in", tmp_path / "out", TARGET)
        assert len(encodes) == 1

    def test_gives_up_after_max_attempts(
        self,
        monkeypatch: pytest.MonkeyPatch,
        encodes: list[tuple[float, float]],
        tmp_path: Path,
        caplog: pytest.LogCaptureFixture,
    ) -> None:
        self._fake_peaks(monkeypatch, [-1.0, -1.1, -1.2, -1.3])
        with (
            caplog.at_level(logging.INFO, logger=audio.logger.name),
            pytest.raises(LoudnessError, match="true peak still above"),
        ):
            normalize_loudness(tmp_path / "in", tmp_path / "out", TARGET)
        assert len(encodes) == 4
        # The per-attempt peaks are visible at INFO.
        (record,) = [r for r in caplog.records if r.levelno == logging.INFO]
        assert "-1.00, -1.10, -1.20, -1.30" in record.getMessage()


