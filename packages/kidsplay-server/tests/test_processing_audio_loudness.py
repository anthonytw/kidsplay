class TestLoudnessConfig:
    def test_defaults(self) -> None:
        cfg = LoudnessConfig()
        assert cfg.enabled
        assert cfg.target_for(MediaType.MUSIC) == TARGET
        # Audiobooks get the same target unless configured otherwise.
        assert cfg.target_for(MediaType.AUDIOBOOK) == TARGET

    def test_per_type_targets(self) -> None:
        cfg = LoudnessConfig(
            target_lufs=-18.0,
            true_peak_dbtp=-2.0,
            music_target_lufs=-14.0,
            audiobook_target_lufs=-12.0,
        )
        assert cfg.target_for(MediaType.MUSIC) == LoudnessTarget(-14.0, -2.0)
        assert cfg.target_for(MediaType.AUDIOBOOK) == LoudnessTarget(-12.0, -2.0)
        assert cfg.target_for(MediaType.PHOTO) == LoudnessTarget(-18.0, -2.0)

    def test_unset_type_target_falls_back(self) -> None:
        cfg = LoudnessConfig(target_lufs=-20.0, audiobook_target_lufs=-14.0)
        assert cfg.target_for(MediaType.MUSIC).integrated_lufs == -20.0

    @pytest.mark.parametrize(
        "make",
        [
            lambda: LoudnessConfig(target_lufs=-4.0),
            lambda: LoudnessConfig(target_lufs=-71.0),
            lambda: LoudnessConfig(music_target_lufs=0.0),
            lambda: LoudnessConfig(audiobook_target_lufs=-80.0),
            lambda: LoudnessConfig(true_peak_dbtp=0.5),
            lambda: LoudnessConfig(true_peak_dbtp=-10.0),
        ],
    )
    def test_out_of_range_rejected(self, make: Callable[[], LoudnessConfig]) -> None:
        with pytest.raises(ValueError, match="must be between"):
            make()


